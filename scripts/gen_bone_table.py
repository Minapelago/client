"""Writes src/mth/core/game/bone_table.inc from the apworld's bones.csv.

Usage:
    python3 -I scripts/gen_bone_table.py ../world [src/mth/core/game/bone_table.inc]
"""

import csv
import sys
from pathlib import Path

LOC_BASE = 10000


def main() -> None:
    world_dir = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "src/mth/core/game/bone_table.inc"
    csv_path = world_dir / "worlds/mina_the_hollower/data/locations/bones.csv"
    with open(csv_path, newline="", encoding="utf-8") as f:
        src = list(csv.DictReader(f))

    rows = []
    seen = set()
    for i, r in enumerate(src):
        ap_id = r["ap_id"]
        try:
            key = int(r["key"], 16)
            x, y = int(r["x"]), int(r["y"])
            ok = (
                int(ap_id) == LOC_BASE + i
                and r["status"] in ("include", "exclude")
                and len(r["key"]) == 16
                and key != 0
                and key not in seen
                and 0 <= int(r["tracker_screen"]) <= 0xFFFFFFFF
                and 0 <= x <= 0xFFFF
                and 0 <= y <= 0xFFFF
            )
        except ValueError:
            ok = False
        if not ok:
            sys.exit(f"bones.csv: bad row at ap_id {ap_id}")
        seen.add(key)
        rows.append((key, i, int(r["tracker_screen"]), x, y, r["status"] == "exclude"))

    rows.sort()
    lines = [
        "// Generated by scripts/gen_bone_table.py from the apworld's data/locations/bones.csv. Do not edit.",
        "// {key, index, screen ((gamestate << 16) | room), x, y (level pixels, y down), excluded}, sorted by key.",
    ]
    lines += [f"{{0x{k:016x}ull, {i}, 0x{s:08x}u, {x}, {y}, {'true' if e else 'false'}}}," for k, i, s, x, y, e in rows]
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(rows)} rows, {sum(r[5] for r in rows)} excluded)")


if __name__ == "__main__":
    main()
